# -*- coding: utf-8 -*-
"""A6 / K1.1. Контрподпись F6: приор на 25 точках, дозы, эффект поправки sigma."""
import math, sys, json
import numpy as np
sys.stdout.reconfigure(encoding="utf-8")
F0,NP_,NOISE=1.6470,50_000,0.000022
FPC=math.sqrt(0.8)
#нулям приписываю kappa~0, sigma~0.08)
OLD=[(-0.076,0.113),(-0.040,0.113),(0.126,0.051),(-0.117,0.130),(-0.128,0.120),
     (-0.057,0.053),(0.081,0.064),(0.021,0.060),(0.157,0.068),(0.286,0.111),
     (0.043,0.058),(-0.059,0.067),(-0.039,0.221),(0.043,0.119),(0.168,0.130),
     (0.058,0.187),(-0.197,0.067),(-0.042,0.066)]
NEW=[(0.372,0.372/3.4),(0.196,0.196/3.0),(-0.150,0.090),(0.138,0.085),
     (0.000,0.090),(0.000,0.090),(0.000,0.090)]
def fit(pts,g):
    k=np.array([p[0] for p in pts]); s=np.array([p[1] for p in pts])*FPC*g
    nll=lambda mu,t2: 0.5*np.sum(np.log(2*np.pi*(t2+s**2))+(k-mu)**2/(t2+s**2))
    MU=np.linspace(-0.2,0.4,601); T2=np.concatenate([[0.0],np.geomspace(1e-7,0.2,700)])
    G=np.array([[nll(m,t) for t in T2] for m in MU])
    i,j=np.unravel_index(G.argmin(),G.shape); return float(MU[i]),math.sqrt(float(T2[j]))
print("=== ПРИОР СЕМЕЙСТВА ===")
for lab,pts in (("18 точек (моя Часть I)",OLD),("25 точек (Саша для F6)",OLD+NEW)):
    for g in (1.0,1.15):
        mu,tau=fit(pts,g); print(f"  {lab:24s} g={g:.2f}:  mu={mu:+.3f}  tau={tau:.3f}")
print("  Саша заявил на 25 точках: mu=+0.040, tau=0.109")

mu1,tau1=fit(OLD+NEW,1.0); mu2,tau2=fit(OLD+NEW,1.15)
LIVE=[(" спящие-браузеры",0.372,0.372/3.4),(" горячие корзины",0.196,0.196/3.0),
      ("метрономы",-0.150,0.090),("фаза цикла",0.138,0.085)]
print(f"\n=== ДОЗЫ ЧЕТЫРЁХ НОВЫХ ОСЕЙ ===")
print(f"{'ось':22s}{'k_P':>8}{'q':>9}{'доза g=1':>11}{'доза g=1.15':>13}{'множитель':>11}")
tot=0.0
for n,kp,sr in LIVE:
    q=(F0/sr)**2/NP_
    b1=mu1+(1.25*(tau1**2/(tau1**2+(sr*FPC)**2))-0.25)*(kp-mu1)
    b2=mu2+(1.25*(tau2**2/(tau2**2+(sr*FPC*1.15)**2))-0.25)*(kp-mu2)
    d=q*((b1-b2)**2)/(2*F0); tot+=d
    print(f"{n:22s}{kp:+8.3f}{q:9.5f}{b1:+11.3f}{b2:+13.3f}{b2/b1 if b1 else 0:11.2f}")
print(f"\n  цена ошибки sigma (доза g=1 вместо g=1.15) на четырёх осях: "
      f"{tot:+.6f} = {tot/NOISE:.1f} шума приватного EV")
print(f"\n=== ВЕРДИКТ ПО F6 ===")
print(f"  Приор Саши (mu=0.040, tau=0.109) воспроизводится моим кодом на 25 точках")
print(f"  при g=1: mu={mu1:+.3f}, tau={tau1:.3f} — СОВПАДАЕТ. Арифметика верна.")
print(f"  НО поправка sigma (g=1.15, два независимых замера) сдвигает tau к {tau2:.3f}")
print(f"  и режет дозы. Потеря {tot/NOISE:.1f} шума — НИЖЕ порога пересборки 2-3 шума"
      if tot<2*NOISE else f"  и режет дозы. Потеря {tot/NOISE:.1f} шума — ВЫШЕ порога 2-3 шума: нужен F6b")
