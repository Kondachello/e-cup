"""P6. Оптимальная финальная пара. В зачёт идёт ЛУЧШИЙ из двух приватных скоров.
Ценность второго слота при отставании D и разбросе разности sigma_d:
(меньше — лучше по RMSLE, поэтому D = насколько файл 2 ХУЖЕ по ожиданию)"""
import numpy as np
from scipy.stats import norm
SE_PRIV=0.0028
def slot2(D, sd):
    z=D/sd
    return sd*norm.pdf(z) - D*norm.cdf(-z)
print("sigma_d — разброс РАЗНИЦЫ приватных скоров двух файлов.")
print("Для почти одинаковых файлов (корр 0.9999) он крошечный; для структурно разных — больше.\n")
print(f"{'sigma_d':>9} " + " ".join(f"{d:>9.5f}" for d in (0,0.0001,0.0003,0.0006,0.0010)))
print(f"{'':9} " + " ".join(f"{'D='+str(d):>9}" for d in (0,0.0001,0.0003,0.0006,0.0010)))
for sd in (0.0002,0.0005,0.0010,0.0020):
    print(f"{sd:>9.4f} " + " ".join(f"{slot2(d,sd):>9.6f}" for d in (0,0.0001,0.0003,0.0006,0.0010)))
print("\n=== ТЕКУЩИЕ КАНДИДАТЫ (замеренные) ===")
C=[("V3_canon",1.6472249545),("V2_tfm3b_opt",1.6472259177),("V1_tfm3b_pre",1.647284324),
   (1.6472995484),(1.6473012822),(1.6473141057),
   (1.6473389766),(1.6479652993)]
best=C[0][1]
print(f"{'файл':20s} {'public':>12} {'отставание D':>13} {'ценность 2-го слота при sd':>28}")
print(f"{'':20s} {'':12} {'':13} {'0.0002':>9} {'0.0010':>9} {'0.0020':>9}")
for nm,s in C:
    D=s-best
    print(f"{nm:20s} {s:>12.7f} {D:>13.7f} " + " ".join(f"{slot2(D,sd):>9.6f}" for sd in (0.0002,0.0010,0.0020)))
print(f"\nПРАВИЛО: второй слот окупается, если ценность > {0.000022:.6f} (уровень шума).")
