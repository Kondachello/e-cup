# -*- coding: utf-8 -*-
"""K4. План вскрытия: что РАЗЛИЧИМО двумя приватными числами.

Ключ: приватный скор файла X раскладывается как
    priv(X) = pub(X) + Delta_level + over(X)
где Delta_level — разница трудности подвыборок (ОДНА И ТА ЖЕ для всех наших
файлов с точностью до члена mean(t^2), они лежат в 0.002 друг от друга),
а over(X) — переоценка от подгонки, файл-специфична.

Отсюда РОВНО ДВА наблюдаемых:
  D = priv(F7) - priv(T3)          — Delta_level СОКРАЩАЕТСЯ, чистый тест переноса
  L = priv(T3) - pub(T3)           — Delta_level + over(T3), КОНФАУНД
"""
import math, sys, json
import numpy as np
sys.stdout.reconfigure(encoding="utf-8")
F7,T3 = 1.6458557351, 1.6469321992541033
DP = F7-T3
PRED_D, SD_D = -0.0011, 0.00030
print("=== РАЗЛОЖЕНИЕ ===")
print(f"  паблик:  F7 {F7:.7f}   T3 {T3:.7f}   разность {DP:+.7f}")
print(f"  D = priv(F7)-priv(T3) = {DP:+.7f} + [over(F7)-over(T3)]")
print(f"  мой прогноз D = {PRED_D:+.5f} => over(F7)-over(T3) = {PRED_D-DP:+.7f}")
print(f"  т.е. добавки F7 переносятся на {PRED_D/DP*100:.0f}% публичного выигрыша")
print("  (>100% ожидаемо: редозы УХУДШАЮТ паблик и УЛУЧШАЮТ приват)")

print("\n=== ЧТО РАЗЛИЧИМО, А ЧТО НЕТ ===")
print("  D  — Delta_level сокращается, значит это ЧИСТЫЙ замер переноса. Различимо.")
print("  L  — Delta_level НЕ отделяется от over(T3) нашими двумя файлами. НЕ различимо,")
print("       пока не станет виден приват хотя бы одного НЕПОДОГНАННОГО файла.")
print("  РЕШЕНИЕ: sample_submit. У него подгонки НОЛЬ по построению, значит")
print("       priv(sample) - pub(sample) = Delta_level ТОЧНО. Одно число закрывает конфаунд")
print("       и переводит L из неразличимых в различимые.")

print("\n=== ТАБЛИЦА 1: вердикт по D (закон переноса, У1) ===")
B=[(-9,-0.0017,"перенос СИЛЬНЕЕ прогноза","усадка была слишком осторожной; w_p занижает"),
   (-0.0017,-0.0005,"ПОДТВЕРЖДЁН","ядро теории верно, дозы правильные"),
   (-0.0005,-0.0001,"перенос СЛАБЕЕ","w_p завышает; сегментные оси переносятся хуже"),
   (-0.0001,0.0,"нулевой","добавки F7 на привате не стоят ничего"),
   (0.0,9,"УБИТ","F7 ХУЖЕ T3: редозы отдали настоящий выигрыш")]
print(f"{'диапазон D':>26}{'вердикт':>26}  следствие")
for lo,hi,v,c in B:
    r=f"[{lo:+.4f}, {hi:+.4f}]" if lo>-9 else f"D < {hi:+.4f}"
    if hi==9: r=f"D >= {lo:+.4f}"
    print(f"{r:>26}{v:>26}  {c}")
print(f"  вероятности по моему прогнозу N({PRED_D},{SD_D}):")
from math import erf,sqrt
Phi=lambda z:0.5*(1+erf(z/sqrt(2)))
for lo,hi,v,_ in B:
    p=Phi((min(hi,9)-PRED_D)/SD_D)-Phi((max(lo,-9)-PRED_D)/SD_D)
    print(f"      {v:26s} {p*100:5.1f}%")

print("\n=== ТАБЛИЦА 2: вердикт по over(T3) (переоценка, У2) — ТОЛЬКО с sample_submit ===")
for lo,hi,v in [(-9,0.0,"переоценки НЕТ — публичная обратная связь нас не переобучала"),
                (0.0,0.00042,"переоценка МЕНЬШЕ моей нижней оценки"),
                (0.00042,0.00068,"ПОДТВЕРЖДЕНА (мой интервал)"),
                (0.00068,0.0014,"выше моей верхней оценки, но порядок тот"),
                (0.0014,9,"вдвое больше верхней — счёт неполон и после аудита")]:
    r=f"< {hi:.5f}" if lo<-8 else (f">= {lo:.5f}" if hi>8 else f"[{lo:.5f}, {hi:.5f}]")
    print(f"  {r:>22}  {v}")

print("\n=== ТАБЛИЦА 3: СОВМЕСТНЫЕ вердикты (что различает пара D x over) ===")
print(f"  {'D':^14}{'over(T3)':^14}  диагноз")
J=[("в норме","в норме","теория верна целиком — базовый сценарий"),
   ("в норме","мала","перенос верен, но публика нас НЕ переобучала: значит наша"),
   ("","","   осторожность стоила паблика зря, а приват от неё не выиграл"),
   ("в норме","велика","перенос верен, но счёт переоценки неполон и после аудита K1"),
   ("убит","в норме","w_p неверен ПРИ верной картине переобучения — ошибка именно"),
   ("","","   в формуле анти-корреляции, а не в бухгалтерии"),
   ("убит","мала","обе части теории неверны: публика и приват просто разные выборки"),
   ("убит","велика","переобучение есть, но лечили не тем — усадка не тот инструмент")]
for a,b,c in J: print(f"  {a:^14}{b:^14}  {c}")

print("\n=== ЧЕГО ДВА ЧИСЛА НЕ СКАЖУТ ===")
print("  1. Поосно: какая из ~35 доз была права. D — сумма, слагаемые не разделяются.")
print("  2. bias(n) поля (У4) — нужна ЧУЖАЯ таблица паблик/приват, не наши два числа.")
print("  3. Витрину (У3) — нужен приват SHOW11; если платформа его не покажет,")
print("     утверждение останется непроверенным, и это надо признать, а не переписать.")
print("  4. Delta_level без sample_submit. Это главный запрос к платформе.")
json.dump(dict(pred_D=PRED_D,sd=SD_D,pub_diff=DP),
          open("out/k4_autopsy.json","w",encoding="utf-8"),ensure_ascii=False,indent=1)

print("\n=== МОЩНОСТЬ ТЕСТОВ: НЕУДОБНАЯ НАХОДКА ===")
D0 = DP        # наивная нулевая: приватный выигрыш = публичному, перенос 1:1
D1 = PRED_D    # моя теория
print(f"  наивная нулевая H0 «перенос 1:1»:  D0 = {D0:+.7f}")
print(f"  моя теория            H1:          D1 = {D1:+.7f}")
print(f"  расхождение |-D0| = {abs(D1-D0):.7f} при sd = {SD_D:.5f}")
print(f"  РАЗДЕЛЕНИЕ = {abs(D1-D0)/SD_D:.2f} сигмы  ->  мощность практически НУЛЕВАЯ")
print("  ВЫВОД: D НЕ отличает мою теорию от наивной. Интервал [-0.0017,-0.0005]")
print("  накрывает и H0, и H1. Тест У1 в такой форме проверяет лишь, что мы не")
print("  сломали файл целиком, а не то, что усадка была права.")
print("\n  ПОЧЕМУ ТАК: F7 и T3 различаются ПАКЕТОМ (редозы + новые оси). Редозы")
print("  ухудшают паблик и улучшают приват, новые оси улучшают оба. В сумме")
print("  эффекты почти гасятся, и предсказания двух теорий сходятся.")
print("  Чистый тест требовал бы файла «F7 БЕЗ редоз» — в паре его нет.")

print("\n=== ЧТО ЗАТО ИМЕЕТ ПОЛНУЮ МОЩНОСТЬ ===")
print("  over(T3) = priv(T3) - pub(T3) - Delta_level")
print(f"    H0 (публика не переобучала): over = 0")
print(f"    H1 (мой аудит):              over = 0.000548 [0.000416, 0.000680]")
print("  Платформа ДЕТЕРМИНИРОВАНА, sample_submit не подогнан => Delta_level")
print("  измеряется ТОЧНО, и over(T3) тоже. Ошибка измерения НОЛЬ.")
print("  Разделение H0/H1 = бесконечность. Это единственный тест кампании")
print("  с полной мощностью, и он стоит ОДНОГО числа с платформы.")
print("\n  ПРИОРИТЕТ K4: просить приватный скор sample_submit. Без него главное")
print("  утверждение теории (переоценка существует и равна 0.0005) непроверяемо.")
