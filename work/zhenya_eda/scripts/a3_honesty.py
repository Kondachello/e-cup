"""A3. АУДИТ: ВЕРНО ЛИ МЫ МЕРЯЕМ ЧЕСТНОСТЬ.

Определение: переоценка = (публичный выигрыш, который мы видели)
                        - (ожидаемый приватный выигрыш при той же дозе)
             = q * b * (kappa_P - E[kappa_Q]) / F0

Проверяем ПОЛНОТУ: все ли дозированные по паблику шаги посчитаны.
"""
import math, sys, json
import numpy as np
sys.stdout.reconfigure(encoding="utf-8")
F0,NP_,NOISE=1.6470,50_000,0.000022
FPC=math.sqrt(0.8); G=1.15
law=lambda q,g=1.0: g*FPC*F0/math.sqrt(NP_*q)
MU_R,TAU_R=0.309,0.196

print("=== 1. МИНИМАЛЬНАЯ ПЕРЕОЦЕНКА НЕУСТРАНИМА ===")
print("  Даже при ИДЕАЛЬНОЙ приватной дозе b=E[k_Q] переоценка = q*b*(k_P-b)/F0 > 0,")
print("  потому что k_P всегда дальше от приора, чем E[k_Q]. Усадка минимизирует")
print("  ПОТЕРЮ к оракулу, а НЕ переоценку. Переоценка — цена самого факта, что мы")
print("  дозируем по публичной обратной связи.\n")
print("  Безусловная переоценка на ОДНО подогнанное направление (сырая доза):")
for g in (1.0,G):
    v=1.25*g*g*(1-NP_/250_000)*F0/NP_
    print(f"    g={g:.2f}:  2.5*sigma^2*q/(2F0) = {v:.3e} = {v/NOISE:.1f} шума  "
          f"(НЕ зависит от q и от силы сигнала)")

print(f"\n=== 2. ПОЛНОТА УЧЁТА: что я НЕ считал в Частях F/G ===")
#итог 0.000416
M1_TOTAL=0.000416
# 8 шагов ДО M1 (finalists.md): их дозы тоже ставились по LB
PRE=[("A1-> посегментная сезонность",0.000679),("-> февральское направление",0.000650),
     ("-> модели второй волны",0.001921),("-> fusion",0.001008),
     ("->",0.000119),("->F4",0.000050),("F4->G2",0.000156),("G2->",0.000068)]
per=1.25*G*G*(1-0.2)*F0/NP_
print(f"  (а) ВОСЕМЬ шагов эпохи до M1 (finalists.md) — ни один не в моём счёте:")
for n,g_ in PRE: print(f"      {n:34s} публичный выигрыш {g_:.6f}")
print(f"      безусловная переоценка: 8 x {per:.3e} = {8*per:.6f} = {8*per/NOISE:.1f} шума")
# (б) сегментные дозы F1..F6
SEGD=[("",0.02086,0.126,0.095),("",0.01173,0.157,0.097),("",0.00440,0.286,0.091),
      ("",0.01209,-0.197,-0.111),(" спящие-браузеры",0.0100,0.372,0.206),
      (" горячие корзины",0.0100,0.196,0.111),("P?? метрономы",0.0100,-0.150,-0.085),
      ("P?? фаза цикла",0.0100,0.138,0.078)]
tot_seg=0.0
print(f"\n  (б) сегментные дозы F1..F6 — тоже не в счёте Части G:")
print(f"      {'ось':22s}{'q':>9}{'k_P':>8}{'доза':>8}{'переоценка':>12}{'шумов':>8}")
for n,q,kp,b in SEGD:
    ov=q*abs(b)*abs(kp-b)/F0; tot_seg+=ov
    print(f"      {n:22s}{q:9.5f}{kp:+8.3f}{b:+8.3f}{ov:12.6f}{ov/NOISE:8.1f}")
print(f"      {'ИТОГО сегментные':22s}{'':>25}{tot_seg:12.6f}{tot_seg/NOISE:8.1f}")

TOT=M1_TOTAL+8*per+tot_seg
print(f"\n=== 3. ИСПРАВЛЕННЫЙ ИТОГ ===")
print(f"  эпоха M1 (то, что я считал):        {M1_TOTAL:.6f} = {M1_TOTAL/NOISE:5.1f} шума")
print(f"  восемь шагов до M1 (пропущено):     {8*per:.6f} = {8*per/NOISE:5.1f} шума")
print(f"  сегментные дозы F1..F6 (пропущено): {tot_seg:.6f} = {tot_seg/NOISE:5.1f} шума")
print(f"  --------------------------------------------------------")
print(f"  НАКОПЛЕННАЯ ПЕРЕОЦЕНКА:            {TOT:.6f} = {TOT/NOISE:5.1f} шума")
print(f"  порог доктрины 0.000500 = 22.7 шума  ->  ПРЕВЫШЕН ВТРОЕ")
print(f"\n  E[приват F5] = паблик + переоценка = 1.6462976 + {TOT:.6f} = {1.6462976+TOT:.6f}")
print(f"  (в Части J стояло 1.6464252 — занижено на {TOT-0.000128:.6f})")

print(f"\n=== 4. КВАДРАТИЧНАЯ ЛЕММА ЧАСТИ J — ПЕРЕФОРМУЛИРОВКА ===")
print("  В Части J написано «покупка дисперсии передозом — ЗАВЕДОМО проигрышная")
print("  сделка». Это СЛИШКОМ СИЛЬНО и противоречит моей же таблице (s=1.5 давало")
print("  +0.37 п.п.). Верная формулировка выводится точно:")
print("    E(b) = E* - a(b-b*)^2,  sd(b) = s*b,  цель: max (E(b)-D_цель)/sd(b)")
print("    => внутренний оптимум СУЩЕСТВУЕТ:  b_ранг = sqrt(b*^2 + D/a) > b*")
print("  То есть передоз по рангу оправдан, но выигрыш ОГРАНИЧЕН и у нас мал.")
print("  Вывод Части J (лотерея не окупается) не меняется — меняется обоснование:")
print("  дело не в том, что рычага нет, а в том, что он короткий И скоррелирован.")
json.dump(dict(total=TOT,m1=M1_TOTAL,pre=8*per,seg=tot_seg,g=G),
          open("out/a3_honesty.json","w",encoding="utf-8"),ensure_ascii=False,indent=1)
