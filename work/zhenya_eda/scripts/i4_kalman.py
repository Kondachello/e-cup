"""I4. РЕАЛИСТИЧНЫЙ ПОЛ: медленную компоненту приходится оценивать по зашумлённой
истории. Установившийся фильтр Калмана для модели
   lp_t = mu + s_t + e_t,  s_t = lam*s_{t-1} + eta,  var(eta)=q(1-lam^2), var(e)=1-p-q
Прогноз lp_{t+1} = mu + lam*s^_t; дисперсия ошибки = P + var(e),
где P — установившаяся дисперсия прогноза состояния: P = lam^2 * P*R/(P+R) + Q.
"""
import numpy as np
p, q, lam = 0.4162, 0.1796, 0.7887
R = 1-p-q                 # белый шум наблюдения
Q = q*(1-lam**2)          # инновация медленной компоненты
P = Q
for _ in range(10000):
    P = lam**2 * (P*R/(P+R)) + Q
V = P*R/(P+R)
err = P + R
sd = 2.2883
print(f"параметры: var(mu)={p:.4f} var(s)={q:.4f} lam={lam:.4f} var(e)={R:.4f}")
print(f"установившаяся дисперсия прогноза состояния P={P:.5f}, фильтрации V={V:.5f}")
print(f"\n=== ТРИ УРОВНЯ ===")
lv = [("белый шум — неустраним никогда", R),
      ("реалистичный пол (Калман по истории)", err),
      ("оптимистичный пол (s_t известна точно)", q*(1-lam**2)+R)]
for nm, e in lv:
    print(f"  {nm:42s} доля дисперсии {e:.4f}  RMSLE {sd*np.sqrt(e):.4f}")
sb = 1.666395
real = sd*np.sqrt(err)
print(f"\n  действующий бленд                          {sb:.4f}")
print(f"  запас до РЕАЛИСТИЧНОГО пола                {sb-real:+.4f}")
print(f"  разрыв до топ-1                             0.0031")
print(f"\n  бленд извлёк {100*(1-(sb/sd)**2)/(1-err):.1f}% того, что вообще извлекаемо")
print(f"\nОГОВОРКИ: (1) модель оценена по 5 точкам автокорреляции; (2) она не знает")
print(f"про сезонность и общий рост, которые модель команды использует и которые")
print(f"добавляют предсказуемости; (3) 30-дневные окна — грубая сетка. Поэтому")
print(f"число — ориентир порядка величины, а не точная граница.")
