"""K4. Ценность зонда. Выводим аналитически, сколько стоит потратить попытку
на ИЗМЕРЕНИЕ оси вместо того, чтобы применить её по приору."""
import numpy as np
TAU, SE = 0.205, 0.332          # разброс κ между осями / ошибка одного замера (часть A)
W = TAU**2/(TAU**2+SE**2)
M = 0.333                        # средняя κ
print(f"приорный разброс κ между осями  τ = {TAU}")
print(f"ошибка одного замера κ          s = {SE}")
print(f"вес замера в апостериоре        w = τ²/(τ²+s²) = {W:.3f}\n")
print("Ось с валидационным выигрышем G (если бы κ=1). Применяем долю c, получаем (2cκ - c²)·G.\n")
print("БЕЗ ЗОНДА: c = m  ->  E[выигрыш] = m²·G")
print(f"   при m={M}:  {M**2:.4f}·G\n")
print("С ЗОНДОМ:  c = m + w(κ̂-m)  ->  E[выигрыш] = (m² + w·τ²)·G")
print(f"   {M**2:.4f}·G + {W*TAU**2:.4f}·G = {M**2+W*TAU**2:.4f}·G\n")
print(f">>> ЦЕННОСТЬ ЗОНДА = w·τ²·G = {W*TAU**2:.4f}·G  — то есть {100*W*TAU**2:.1f}% выигрыша оси")
print(f">>> а простое применение по приору даёт {100*M**2:.1f}% — В {M**2/(W*TAU**2):.0f} РАЗ БОЛЬШЕ\n")
print("=== СЛЕДСТВИЕ: зонд окупается только если оси НЕТ на валидации ===")
print("Тип L (ось измерима локально, G известна): зондировать НЕ НАДО, применять по приору.")
print("Тип S (структурная, на вале не существует): зонд — единственный способ, ценность = весь выигрыш.\n")
q = 0.0002
print(f"Для типа S при цене направления q={q}: выигрыш k²·q, усадка a = max(0, 1 - s²/k̂²)")
print(f"{'истинная k':>11} {'E[выигрыш] после усадки':>25} {'сигм в замере':>14}")
for k in (1.0, 0.8, 0.6, 0.5, 0.4, 0.3):
    a = max(0.0, 1-SE**2/(k**2+SE**2))
    print(f"{k:>11.1f} {a*k*k*q:>25.6f} {k/SE:>14.1f}")
print(f"\nпорог: ось типа S стоит зонда, если ожидаемая |k| >= {SE:.2f} (1 сигма),")
print(f"иначе усадка съедает больше половины и E[выигрыш] < {SE**2*q:.6f}")
print(f"\n=== ЦЕНА ПРИМЕНЕНИЯ ОСИ (фиктивный выигрыш на паблике) ===")
print(f"каждое подобранное направление добавляет 0.000022 переоценки паблика (их замер)")
print(f"значит применять ось стоит, только если E[тестовый выигрыш] > 0.000022")
