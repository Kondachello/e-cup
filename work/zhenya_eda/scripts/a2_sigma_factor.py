"""A2. АУДИТ: занижена ли sigma_kappa, и что это делает с дозами.

Путь 1 (a1): прямая симуляция раскола — sd(kappa_P) факт / закон = 1.17-1.62.
Путь 2 (здесь): семейства осей. Если sigma занижена в g раз, то
   Var(kappa_hat) = tau^2 + g^2*<sigma_law^2>
Для РАЗЛОЖЕНИЯ теория требует tau_z ~ 0 (исчерпывающее разложение уже
дозированного оптимума, Часть F §2.2). Отсюда g оценивается из данных.
"""
import math, sys, json
import numpy as np
sys.stdout.reconfigure(encoding="utf-8")
F0,NP_,NOISE=1.6470,50_000,0.000022
FPC=math.sqrt(0.8)
law=lambda q: FPC*F0/math.sqrt(NP_*q)

Z=[(0.02470,+0.010),(0.21957,+0.006),(0.03475,-0.064),(0.13151,-0.012),(0.06326,+0.034),
   (0.06581,+0.032),(0.11696,-0.071),(0.03773,+0.037),(0.03854,-0.041),(0.02630,+0.013),
   (0.02910,+0.009),(0.04377,-0.037),(0.11421,+0.015),(0.06681,-0.018),(0.04703,-0.007),
   (0.25102,-0.005),(0.03788,-0.057),(0.03707,+0.014),(0.38802,-0.025),(0.34704,-0.015)]
kz=np.array([x[1] for x in Z]); sz=np.array([law(x[0]) for x in Z])
V=np.var(kz,ddof=1); S2=np.mean(sz**2)
print("=== ПУТЬ 2: семейство Z-РАЗЛОЖЕНИЯ (теория требует tau_z ~ 0) ===")
print(f"  Var(kappa_hat) = {V:.6f},  <sigma_закон^2> = {S2:.6f}")
print(f"  если tau_z = 0 ровно, то g = sqrt(V/<s^2>) = {math.sqrt(V/S2):.3f}")
print(f"  (при g=1 остаётся tau_z = {math.sqrt(max(V-S2,0)):.4f} — то, что мы считали)")

print(f"\n=== СВОДКА ПО ДВУМ ПУТЯМ ===")
print(f"  путь 1 (прямая симуляция на вал-таргете): g = 1.17 … 1.62")
print(f"  путь 2 (разложение при tau_z=0):          g = {math.sqrt(V/S2):.2f}")
print(f"  ОБА пути в одну сторону: sigma ЗАНИЖЕНА. Консервативная оценка g = 1.15")

G=1.15
print(f"\n=== ЧТО ЭТО ДЕЛАЕТ С ДОЗАМИ (g = {G}) ===")
SEGF=[("",0.02086,+0.126),("",0.01173,+0.157),("",0.00440,+0.286),
      ("",0.01209,-0.197),("P52_sleepbrow",0.0100,+0.372),("P50_hotcart",0.0100,+0.196)]
def fam_fit(k,s):
    nll=lambda mu,t2: 0.5*np.sum(np.log(2*np.pi*(t2+s**2))+(k-mu)**2/(t2+s**2))
    MU=np.linspace(-0.3,0.6,901); T2=np.concatenate([[0.0],np.geomspace(1e-7,0.2,700)])
    g_=np.array([[nll(m,t) for t in T2] for m in MU])
    i,j=np.unravel_index(g_.argmin(),g_.shape); return float(MU[i]),math.sqrt(float(T2[j]))
SEG=[(-0.076,0.113),(-0.040,0.113),(0.126,0.051),(-0.117,0.130),(-0.128,0.120),
     (-0.057,0.053),(0.081,0.064),(0.021,0.060),(0.157,0.068),(0.286,0.111),
     (0.043,0.058),(-0.059,0.067),(-0.039,0.221),(0.043,0.119),(0.168,0.130),
     (0.058,0.187),(-0.197,0.067),(-0.042,0.066)]
ks=np.array([x[0] for x in SEG]); ss=np.array([x[1] for x in SEG])*FPC
for g in (1.0,G):
    mu,tau=fam_fit(ks,ss*g)
    print(f"  g={g:.2f}: приор семейства mu={mu:+.3f}, tau={tau:.3f}")
    for nm,q,kp in SEGF:
        sg=law(q)*g; w=tau*tau/(tau*tau+sg*sg); wp=1.25*w-0.25
        print(f"      {nm:14s} q={q:.5f} kappa={kp:+.3f}  w={w:.3f} w_p={wp:+.3f} "
              f"доза={mu+wp*(kp-mu):+.3f}")
