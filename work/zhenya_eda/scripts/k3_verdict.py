"""K3. Вердикт по части A: предсказуема ли κ поштучно."""
import numpy as np
from scipy import stats
K = np.array([0.601,0.529,0.307,0.00,-0.20,0.05,0.20,0.09,0.63,1.12])
NM = ["бленд1","бленд2","стек1","стек2","своп","сегмент","уровень","e_new","дешринк","крошки"]
CLS= ["бленд","бленд","стек","стек","своп","сегмент","уровень","остаток","проба","крошка"]
SE = 0.332          # установлено тремя способами
print(f"SE(κ) = {SE} — установлено независимо тремя способами:")
print("  1) их пять проб: k/сигмы дают 0.319..0.335, среднее 0.328")
print("  2) их же рецепт усадки a = max(0, 1 - 0.11/k^2): 0.11 = SE^2 -> SE = 0.332")
print("  3) мой прямой расчёт SE коэффициента оси на 50k публики (k2_kappa_se.py)\n")

chi2 = float(np.sum((K-K.mean())**2)/SE**2); df = len(K)-1
p = 1-stats.chi2.cdf(chi2, df)
print(f"=== ОДНОРОДНОСТЬ 10 ТОЧЕК ===")
print(f"  среднее κ = {K.mean():.3f}, наблюдаемый sd = {K.std(ddof=1):.3f}")
print(f"  хи-квадрат = {chi2:.2f} при {df} ст.св., p = {p:.3f}")
print(f"  вердикт: {'ОДНОРОДНЫ — гипотеза общего κ НЕ отвергается' if p>0.05 else 'различимы'}")
excess = K.var(ddof=1) - SE**2
print(f"  избыточная дисперсия сверх шума: {excess:+.4f} "
      f"({'есть' if excess>0 else 'ОТСУТСТВУЕТ'}); истинный разброс κ <= {max(excess,0)**.5:.3f}")

print(f"\n=== ДОСТИЖИМА ЛИ MAE 0.10 ===")
oracle = SE*np.sqrt(2/np.pi)
print(f"  даже ИДЕАЛЬНЫЙ предсказатель даёт против этих мишеней MAE = E|N(0,SE)| = {oracle:.3f}")
print(f"  требуемая MAE 0.10 => нужна SE(κ) <= {0.10/np.sqrt(2/np.pi):.3f}")
print(f"  во сколько раз больше публики нужно: {(SE/(0.10/np.sqrt(2/np.pi)))**2:.1f}x "
      f"=> n = {50000*(SE/(0.10/np.sqrt(2/np.pi)))**2:,.0f} юзеров при доступных 50 000")
print(f"  ВЫВОД: MAE<=0.10 НЕДОСТИЖИМА в принципе, мишени зашумлены сильнее требования")

print(f"\n=== ЧТО ВСЁ-ТАКИ РАЗЛИЧИМО: классы ===")
import collections
g = collections.defaultdict(list)
for k,c in zip(K,CLS): g[c].append(k)
print(f"{'класс':10s} {'n':>2} {'среднее':>9} {'SE':>7}")
est={}
for c,v in g.items():
    m=np.mean(v); s=SE/np.sqrt(len(v)); est[c]=(m,s)
    print(f"{c:10s} {len(v):>2} {m:>9.3f} {s:>7.3f}")
mb,sb_=est["бленд"]; ms,ss=est["стек"]
d=mb-ms; sd_=np.hypot(sb_,ss)
print(f"\n  бленд минус стек: {d:+.3f} +- {sd_:.3f}  ->  {d/sd_:.1f} сигмы "
      f"({'значимо' if abs(d/sd_)>1.96 else 'НЕ значимо'})")
print(f"  то есть даже на уровне КЛАССОВ разделение не достигает 2 сигм при 2 точках на класс")

print(f"\n=== СКОЛЬКО ЗАМЕРОВ НУЖНО, чтобы отличить класс от класса ===")
for d_true in (0.4, 0.3, 0.2):
    n = 2*(1.96*SE/d_true)**2
    print(f"  истинная разница {d_true:.1f}: нужно {n:.0f} замеров на класс "
          f"(это {n*2:.0f} попыток лидерборда только на калибровку κ)")
