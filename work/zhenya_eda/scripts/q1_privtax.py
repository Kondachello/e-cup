"""Q1. Налог на приват: сколько теряет применённая доза оттого, что коэффициент
замерен на 50k публики, а работает на 200k привата.

Вывод. Применяем b вместо оптимального c_true/q:
   потеря = (c_прим - c_ист)² / (q · 2F0)
Без усадки: E[(c_pub - c_priv)²] = V(1/50000 + 1/200000), V = Var(e·h) ≈ F0²q
   => потеря = F0·(1/n_pub + 1/n_priv)/2  — НЕ ЗАВИСИТ от q и от оси
С усадкой w = τ²/(τ²+σ²) (оптимальной по Байесу):
   MSE_κ = τ²σ²/(τ²+σ²),  потеря = MSE_κ·q/(2F0)
"""
import json, numpy as np
F0, NPUB, NPRIV, TAU2, NOISE = 1.666395, 50_000, 200_000, 0.0416, 0.000022
sig2 = lambda q: F0**2/(NPUB*q)

flat = F0*(1/NPUB + 1/NPRIV)/2
print(f"БЕЗ УСАДКИ налог одной оси = F0·(1/n_pub+1/n_priv)/2 = {flat:.7f}")
print(f"  это {flat/NOISE:.2f} шума НА КАЖДУЮ ось, независимо от её величины\n")

print("С УСАДКОЙ (оптимальная доза) налог зависит от q:")
print(f"{'q':>9} {'σ_κ':>7} {'доза w':>7} {'налог':>10} {'в шумах':>8}")
for q in (0.000026,0.00013,0.00066,0.0013,0.0023,0.0028,0.02):
    s2=sig2(q); w=TAU2/(TAU2+s2)
    mse=TAU2*s2/(TAU2+s2); loss=mse*q/(2*F0)
    print(f"{q:>9.6f} {np.sqrt(s2):>7.3f} {w:>7.3f} {loss:>10.7f} {loss/NOISE:>8.2f}")

print(f"\n=== СУММА ПО РЕАЛЬНОМУ РЕЕСТРУ (15 осей) ===")
d=json.load(open("../zhenya/kappa_registry.json",encoding="utf-8"))
tot_sh=tot_fl=0.0
for a in d["axes"]:
    q=float(a["q"]); s2=sig2(q); mse=TAU2*s2/(TAU2+s2)
    tot_sh+=mse*q/(2*F0); tot_fl+=flat
print(f"  с оптимальной усадкой: {tot_sh:.6f} = {tot_sh/NOISE:.1f} шума")
print(f"  если бы дозы применяли БЕЗ усадки: {tot_fl:.6f} = {tot_fl/NOISE:.1f} шума")
print(f"\n  твоя оценка «1-2 шума» — для СУММЫ она занижена: выходит {tot_sh/NOISE:.1f}")
print(f"  (на ось в среднем {tot_sh/len(d['axes'])/NOISE:.2f} шума, что близко к 1-2 ЗА ОСЬ)")
print(f"\n  в RMSLE суммарный налог {tot_sh:.6f} при разрыве до топ-1 ~0.0031")
print(f"  => это {100*tot_sh/0.0031:.1f}% разрыва. Не критично, но и не пренебрежимо.")
print(f"\nВАЖНО: налог НЕ уменьшается от повторных замеров той же оси — он от того,")
print(f"что публика и приват это разные выборки. Уменьшается только увеличением q")
print(f"(при большом q усадка ближе к 1, но и σ мала — налог выходит на плато F0/2n).")
