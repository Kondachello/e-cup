"""N20. Оптимальная трата слотов + приватный прогноз пары.

Ценность ОДНОГО зонда новой оси (замерить, потом дозировать приватно-оптимально):
  E[выигрыш] = q*E[(E[k_Q|k])^2]/(2F0) - q*mu^2/(2F0)   [против дозы вслепую по приору]
             = q*w_p^2*(tau^2+sigma^2)/(2F0)
С sigma^2 = c/q, c = 0.8*F0^2/n_pub, это сворачивается в замкнутую форму:
  V(q, tau) = (tau^2*q - 0.25c)^2 / ((tau^2*q + c) * 2F0)
"""
import math, sys, json
import numpy as np
sys.stdout.reconfigure(encoding="utf-8")
F0,NP_,NOISE=1.6470,50_000,0.000022
c=0.8*F0*F0/NP_
def V(q,tau): 
    A=tau*tau
    return (A*q-0.25*c)**2/((A*q+c)*2*F0) if A*q>0.25*c else 0.0
print(f"c = 0.8*F0^2/n = {c:.3e}   (порог осмысленности зонда: tau^2*q > 0.25c = {0.25*c:.2e})")
FAM={"сегментная когорта":0.086,"новая модельная ось (kevf3)":0.196,
     "ось Z-разложения":0.0148,"молчание (после /41/46)":0.10}
print(f"\n=== ЦЕННОСТЬ ОДНОГО ЗОНДА, шумов привата ===")
print(f"{'семейство':30s}" + "".join(f"q={q:<8.3f}" for q in (0.003,0.01,0.02,0.05)))
for n,t in FAM.items():
    print(f"{n:30s}" + "".join(f"{V(q,t)/NOISE:9.2f} " for q in (0.003,0.01,0.02,0.05)))
print("\n  Порог осмысленности: tau^2*q > 0.25c. Для разложения (tau=0.0148) он")
print(f"  требует q > {0.25*c/0.0148**2:.1f} — недостижимо. Зонды разложения БЕСПОЛЕЗНЫ.")

print(f"\n=== РАНЖИРОВАНИЕ ОСТАВШИХСЯ СЛОТОВ ===")
SLOTS=[("подтверждение финальной сборки","страховка от ошибки сборки, не EV",None,
        "обязателен: цена ошибки = весь выигрыш"),
       ("зонд kevf3 (если придёт)","новая модельная ось, tau=0.196",V(0.003,0.196),None),
       ("новая сегментная когорта","tau=0.086, типичный q=0.015",V(0.015,0.086),None),
       ("дробление уже нулевой когорты","та же tau, но q меньше",V(0.005,0.086),None),
       ("повторный зонд молчания","ось уже добрана в F5",V(0.01,0.10)*0.3,
        "остаточная, доза уже стоит"),
       ("зонд оси Z-разложения","tau=0.0148",V(0.05,0.0148),"ноль по построению"),
       ("lambda-разрез слипа","закрыт расчётом (Часть H §3)",0.0,None)]
rows=[]
for n,d,v,note in SLOTS:
    rows.append((n,d,v,note))
rows.sort(key=lambda r:-(r[2] if r[2] is not None else 1e9))
print(f"{'#':>2} {'слот':32s}{'шумов':>8}  описание")
for i,(n,d,v,note) in enumerate(rows,1):
    vs="—" if v is None else f"{v/NOISE:.2f}"
    print(f"{i:2d} {n:32s}{vs:>8}  {d}" + (f" [{note}]" if note else ""))

print(f"\n=== ПРИВАТНЫЙ ПРОГНОЗ ПАРЫ ===")
PUB={"F5_priv":1.6462975719,"F4_priv":1.6468218952,"T3":1.6469322}
