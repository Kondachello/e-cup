print(f"  Абсолютный уровень: приват = паблик + переоценка + общий сдвиг(SE {SE_ABS})")
print(f"  ВАЖНО: общий сдвиг ОДИНАКОВ для всех участников (одни и те же 200k),")
print(f"  поэтому на РАНГ он не влияет и в сравнение не входит.\n")
print(f"{'файл':10s}{'паблик':>12}{'E[приват]':>12}{'sd разности к F5':>18}")
SD={"F5_priv":0.0,"F4_priv":0.000260,"T3":0.000260}
