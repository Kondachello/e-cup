"""I3. Потолок предсказуемости через структуру автокорреляции таргета.

Замерено (30-дневные окна, лаг в единицах 30 дней):
   r(1)=0.5592 r(2)=0.5243 r(3)=0.5070 r(5)=0.4710 r(8)=0.4429
Раз r(k) УБЫВАЕТ, модель «постоянный уровень + белый шум» неверна, и оценка
пола sd*sqrt(1-r(1)) недействительна. Правильная модель:
   lp_t = mu + s_t + e_t,   s_t = lam*s_{t-1} + eta,   e_t белый
   r(k) = p + q*lam^k,  p=var(mu), q=var(s), var(e)=1-p-q   (нормировка var(lp)=1)
Оптимистичный потолок (s_t наблюдается точно): var ошибки = q*(1-lam^2) + (1-p-q).
"""
import numpy as np
from scipy.optimize import least_squares
k = np.array([1,2,3,5,8], float)
r = np.array([0.5592,0.5243,0.5070,0.4710,0.4429])
f = lambda t: t[0] + t[1]*t[2]**k - r
sol = least_squares(f, [0.40,0.16,0.8], bounds=([0,0,0],[1,1,0.999]))
p,q,lam = sol.x
print(f"подгонка r(k) = p + q*lam^k:  p={p:.4f}  q={q:.4f}  lam={lam:.4f}  невязка={np.abs(sol.fun).max():.5f}")
print(f"  постоянная часть   var(mu) = {p:.4f}")
print(f"  медленная часть    var(s)  = {q:.4f}")
print(f"  белый шум          var(e)  = {1-p-q:.4f}")
print(f"  подогнано:", " ".join(f"r({int(x)})={p+q*lam**x:.4f}" for x in k))

sd = 2.2883
opt = q*(1-lam**2) + (1-p-q)          # s_t известен точно — оптимистично
print(f"\n=== ПОТОЛОК ===")
print(f"  доля дисперсии, предсказуемая в лучшем случае: {1-opt:.4f}")
print(f"  оптимистичный ПОЛ RMSLE: {sd*np.sqrt(opt):.4f}")
print(f"  для сравнения — предиктор «только прошлое окно»: mdl_flint={r[0]**2:.4f} -> RMSLE {sd*np.sqrt(1-r[0]**2):.4f}")
sb = 1.666395
print(f"  действующий бленд: {sb:.4f}, то есть mdl_flint={1-(sb/sd)**2:.4f}")
print(f"\n  запас бленда до оптимистичного пола: {sb - sd*np.sqrt(opt):.4f}")
print(f"  разрыв до топ-1: 0.0031")
print(f"\nОГОВОРКА: пол оптимистичен вдвойне — он предполагает, что медленная")
print(f"компонента s_t наблюдается ТОЧНО, а её приходится оценивать по зашумлённой")
print(f"истории. Реальный достижимый пол ВЫШЕ. Это верхняя граница возможностей,")
print(f"а не обещание.")
