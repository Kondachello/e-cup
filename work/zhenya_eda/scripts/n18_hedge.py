# -*- coding: utf-8 -*-
"""N18. МОДЕЛЬНЫЙ ХЕДЖ T3 В ЧИСЛЕ (блокер решения Саши).

Вопрос: при каком субъективном P(теория неверна)=p пара {F, T3} обгоняет {F, F4}?

Структура. Все выигрыши мерим НАД T3-цепочкой, поэтому T3 = 0 тождественно.
  состояние «теория верна» (1-p): G_F ~ N(g_F, s_F^2), G_4 ~ N(g_4, s_4^2)
  состояние «теория неверна» (p): выигрыши F-серии = -L (обе версии ниже)
Ценность пары = E[лучший из двух].

  V{F,T3} = (1-p)*E[max(G_F,0)] + p*max(-L,0) = (1-p)*E[max(G_F,0)]
  V{F,F4} = (1-p)*E[max(G_F,G_4)] - p*L

Порог:  p* = D / (D + L),   D = E[max(G_F,G_4)] - E[max(G_F,0)]
D — это страховая ценность F4 в хорошем состоянии, L — потеря F-серии в плохом.
"""
import math, sys, json
import numpy as np
from math import erf, exp, sqrt, pi
sys.stdout.reconfigure(encoding="utf-8")
NOISE=0.000022
Phi=lambda z:0.5*(1+erf(z/sqrt(2))); phi=lambda z:exp(-z*z/2)/sqrt(2*pi)
def Emax(mu1,s1,mu2,s2,rho=0.0):
    """E[max(,)] для двух нормальных"""
    sd=math.sqrt(max(s1*s1+s2*s2-2*rho*s1*s2,1e-24)); d=mu1-mu2
    return mu2+ d*Phi(d/sd)+sd*phi(d/sd) if sd>1e-12 else max(mu1,mu2)

CAND={"F3":(0.000333,0.000061),"F5":(0.000923,0.000260)}
G4,S4=0.000254,0.000000
print("=== СТРАХОВАЯ ЦЕННОСТЬ F4 В ХОРОШЕМ СОСТОЯНИИ (D) ===")
print(f"{'финалист-1':10s}{'g_F':>11}{'s_F':>10}{'E[max(F,F4)]':>14}{'E[max(F,0)]':>13}{'D':>12}")
D={}
for n,(g,s) in CAND.items():
    a=Emax(g,s,G4,S4); b=Emax(g,s,0.0,0.0); D[n]=a-b
    print(f"{n:10s}{g:+11.6f}{s:10.6f}{a:14.6f}{b:13.6f}{a-b:12.6f}")

print(f"\n=== ПОРОГ p* = D/(D+L) ===")
print("  L — насколько F-серия ХУЖЕ T3 на привате, если теория неверна.")
print("  Версия (а) Саши: вклад F-серии ~0  =>  L=0  =>  p*=1: T3 НИКОГДА не нужен")
print("    (в плохом состоянии все три кандидата дают одно и то же, решает хорошее).")
print("  Версия (б): знак от передозов эпохи  — L>0, шкала ниже.\n")
LS=[("редоза  отыграна назад",0.000071),("вся редоза + сегментные дозы",0.000150),
    ("все приватные поправки в минус",0.000333),("катастрофа: -2x выигрыша",0.000700),
    ("L = сам выигрыш F5",0.000923)]
print(f"{'сценарий L':34s}{'L':>11}" + "".join(f"{n:>12}" for n in CAND))
for lab,L in LS:
    row=f"{lab:34s}{L:+11.6f}"
    for n in CAND: row+=f"{D[n]/(D[n]+L)*100:11.1f}%"
    print(row)
print(f"\n  Читать так: «если вероятность того, что теория неверна, ВЫШЕ этого числа —")
print(f"  бери T3 вторым; если ниже — бери F4».")

print(f"\n=== ГЛАВНЫЙ ВЫВОД ===")
for n,(g,s) in CAND.items():
    L=0.000150
    print(f"  {n}: D={D[n]:.6f} — страховая ценность F4 КРОШЕЧНАЯ, поэтому порог низкий:")
    print(f"      при L={L:.6f} достаточно p > {D[n]/(D[n]+L)*100:.1f}%, чтобы T3 был лучше.")
json.dump(dict(D=D,scen=[(l,L) for l,L in LS]),open("out/n18_hedge.json","w",encoding="utf-8"),
          ensure_ascii=False,indent=1)
